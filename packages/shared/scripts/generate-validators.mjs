/**
 * Compile the research contract into validators that ship as plain JavaScript.
 *
 * MV3's content-script CSP forbids `new Function`, and that is exactly how Ajv
 * builds a validator at runtime — so the usual `new Ajv().compile(schema)` dies
 * inside an x.com tab with a CSP violation and no useful stack. Ajv's
 * *standalone* mode does the compilation here, at build time, and emits
 * ordinary functions. Nothing is evaluated in the browser.
 *
 *     node scripts/generate-validators.mjs           # check for drift
 *     node scripts/generate-validators.mjs --write   # regenerate
 *
 * The schema itself comes from the Python models
 * (`scripts/export_research_contract.py` in optimai-agentic-server), so the chain is one-way:
 * Pydantic → JSON Schema → these validators. Nothing here is hand-maintained,
 * which is the point — a hand-written check drifts, and the drift shows up as a
 * card that renders `undefined` weeks later.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import Ajv from 'ajv'
import standaloneCode from 'ajv/dist/standalone/index.js'

const here = dirname(fileURLToPath(import.meta.url))
const SCHEMA = join(here, '../lib/agent/research-contract.schema.json')
const OUTPUT = join(here, '../lib/agent/generated/validators.js')

const schema = JSON.parse(readFileSync(SCHEMA, 'utf8'))

/**
 * `strict: false` because the exported schema uses Pydantic's own idioms —
 * `const` beside `enum`, `$defs` Ajv does not need told about. Turning them
 * into errors would mean editing the Python models to please a validator,
 * which is the tail wagging the dog.
 *
 * `allErrors` stays off: this decides whether to render a card, not what to
 * tell an author, and collecting every error on a malformed payload is work
 * nobody reads.
 */
const ajv = new Ajv({
  strict: false,
  allErrors: false,
  code: { source: true, esm: true },
  schemas: Object.fromEntries(
    Object.entries(schema.$defs).map(([name, definition]) => [
      name,
      { ...definition, $id: name, $defs: { ...(definition.$defs ?? {}) } },
    ])
  ),
})
/**
 * Formats declared as regular expressions, not via `ajv-formats`.
 *
 * `ajv-formats` registers its checkers as function references, and standalone
 * mode serialises those as `require('ajv-formats/dist/formats')` — a CommonJS
 * call in a file this package publishes as ESM, which fails to load before it
 * validates anything. A RegExp is inlined into the generated source instead, so
 * the output stays self-contained.
 *
 * These are shape checks, deliberately loose. Whether a timestamp is *real* is
 * settled where it is used — `new Date(...)` and `Number.isFinite` — not here.
 */
ajv.addFormat('date-time', /^\d{4}-\d{2}-\d{2}[Tt]\d{2}:\d{2}:\d{2}(\.\d+)?([Zz]|[+-]\d{2}:\d{2})$/)
ajv.addFormat('uri', /^[a-zA-Z][a-zA-Z0-9+\-.]*:/)

/**
 * Three, not four. `ResearchUIMessage` is deliberately left out: validating a
 * whole message would re-validate every card inside it, which `parseParts`
 * already does part by part — and part by part is the behaviour that matters,
 * because one bad card must cost that card and not the message. Compiling it
 * anyway inlines the entire card union a second time and roughly doubles what
 * ships into every x.com tab.
 */
const ENTRY_POINTS = [
  'ResearchCard',
  'VisualizationSpec',
  'ActivitySnapshot',
  // Repeated elements, validated item by item so one bad post, row or step
  // costs that item rather than the card around it.
  'ResearchPostSnapshot',
  'StanceAnnotation',
  'ComparisonRow',
  'PriceReading',
  'ActivityStep',
]

const exports = Object.fromEntries(ENTRY_POINTS.map((name) => [`validate${name}`, name]))

const banner = `// GENERATED by packages/shared/scripts/generate-validators.mjs, do not edit.
// Source of truth: src/app/agent/presentation_schemas.py in optimai-agentic-server.
// Regenerate: pnpm -F @extension/shared generate:validators
// This file embeds code generated by and derived from Ajv (MIT License,
// Copyright (c) 2015-2021 Evgeny Poberezkin). See THIRD_PARTY_NOTICES.md at the repo root.
/* eslint-disable */
`

/**
 * Ajv's own runtime helpers, inlined.
 *
 * `code: { esm: true }` governs how the *exports* are written; Ajv 8.20 still
 * emits `require("ajv/dist/runtime/ucs2length")` for its internal helpers. That
 * is a CommonJS call in a file this package publishes as ESM, so the module
 * throws on import before it has validated anything.
 *
 * Rewriting it to an `import` was the first attempt and it fails differently
 * and more quietly: the helper is CJS with `exports.default`, so the default
 * import resolves to the module object and every call dies with
 * "func3 is not a function" — at validation time, per card, not at load.
 *
 * So the helper is inlined instead. It is eleven lines, it makes the generated
 * file self-contained with no imports at all, which is what a content script
 * wants anyway. The rewrite is narrow and anything it does not recognise
 * throws here, at build time, rather than shipping.
 */
const UCS2LENGTH = `function ucs2length(str) {
  const len = str.length
  let length = 0
  let pos = 0
  let value
  while (pos < len) {
    length++
    value = str.charCodeAt(pos++)
    if (value >= 0xd800 && value <= 0xdbff && pos < len) {
      value = str.charCodeAt(pos)
      if ((value & 0xfc00) === 0xdc00) pos++
    }
  }
  return length
}`

const inlineRuntime = (source) => {
  let needsUcs2 = false
  const body = source.replace(
    /const (\w+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/g,
    (_match, name) => {
      needsUcs2 = true
      return `const ${name} = ucs2length;`
    }
  )
  if (/\brequire\(/.test(body)) {
    throw new Error(
      'the generated validator still contains a require() this script does not know how ' +
        'to inline; it would throw on import. Inspect the output before shipping it.'
    )
  }
  return needsUcs2 ? `${UCS2LENGTH}\n${body}` : body
}

const generated = banner + inlineRuntime(standaloneCode(ajv, exports))

const write = process.argv.includes('--write')
if (write) {
  writeFileSync(OUTPUT, generated)
  console.log(`wrote lib/agent/generated/validators.js (${generated.length} bytes)`)
  process.exit(0)
}

let current = ''
try {
  current = readFileSync(OUTPUT, 'utf8')
} catch {
  console.error('validators.js does not exist; run with --write')
  process.exit(1)
}

if (current !== generated) {
  console.error(
    'lib/agent/generated/validators.js is out of date with the contract schema; ' +
      'run pnpm -F @extension/shared generate:validators'
  )
  process.exit(1)
}
console.log('validators.js is up to date')
